# Área do retângulo
base = 5
altura = 3
area = base * altura
print("Área do retângulo:", area, "cm²")

# Perímetro do retângulo
perimetro = 2 * base + 2 * altura
print("Perímetro do retângulo:", perimetro, "cm")

# Área do triângulo
base = 6
altura = 4
area = (base * altura) / 2
print("Área do triângulo:", area, "cm²")

# Área do quadrado
lado = 4
area = lado * lado
print("Área do quadrado:", area, "cm²")
